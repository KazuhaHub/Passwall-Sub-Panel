// Further fleets for the compatibility golden: every kind of line, a group
// filter that hides a line, the region-flag prefix, a node-bound separator and a
// non-default sort strategy. Each is rendered in all three formats and compared
// with a golden captured from the pipeline as it was BEFORE per-line ordering
// existed (see TestUpgradeWithoutPositionsRendersIdenticalBytesForEveryScenario).
//
// This file must stay buildable against that older pipeline: it may use only
// what existed then, which is why it never mentions a line position.

// lineKindsFleet: a forward line, a tunnel line (with its hidden listener), a
// CDN line, a disabled relay, and a plain external line, on two landings.
func lineKindsFleet(t *testing.T) *lineOrderRender {
	t.Helper()
	r := newLineOrderRender(t, nil,
		spec(40, "K", 10, "US", "fw", "tn", "off", "ext"),
		spec(42, "W", 20, "JP", "cf"),
	)
	k, w := r.nodes[0], r.nodes[1]
	k.Relays[0].EntryPanelID, k.Relays[0].ManagedReady = 9, true // forward
	child := tunnelListener()
	child.ID, child.ParentNodeID, child.ParentLineID = 41, 40, "tn"
	k.Relays[1].Mode, k.Relays[1].EntryPanelID, k.Relays[1].TunnelNodeID, k.Relays[1].TunnelNode, k.Relays[1].ManagedReady =
		domain.RelayModeTunnel, 9, child.ID, child, true
	k.Relays[2].Enabled = false // disabled relay
	// The tunnel line's client is attached to its hidden listener on server 9.
	repo := r.Service.repos.PSPClient.(lineCredentialRepo)
	for _, c := range repo.clients {
		if c.NodeID == 40 && c.LineID == "tn" {
			c.PanelID = 9
			a := repo.attachments[c.ID]
			a[0].NodeID = child.ID
		}
	}
	r.Service.repos.Node = tunnelNodeRepo{nodes: map[int64]*domain.Node{child.ID: child}}
	r.Service.repos.XUIPanel = renderPanelRepo{kind: domain.PanelKindPSP}

	w.Flow, w.DesiredPort = "", 8443
	w.StreamSettings = cdnWS
	cf := *cdnLine("104.16.1.1")
	cf.ID = "cf"
	w.Relays[0] = cf
	return r
}

// filteredFlaggedFleet: the group's tag filter hides one line and the region
// flag prefix is on.
func filteredFlaggedFleet(t *testing.T) *lineOrderRender {
	t.Helper()
	r := newLineOrderRender(t, nil,
		spec(7, "A", 10, "US", "a1", "a2"),
		spec(8, "C", 20, "JP", "c1"),
		spec(9, "D", 30, "HK", "d1", "d2"),
	)
	for _, n := range r.nodes {
		for i := range n.Relays {
			n.Relays[i].Tags = []string{"keep"}
		}
	}
	r.nodes[2].Relays[1].Tags = []string{"drop"}
	r.nodes[0].Tags, r.nodes[1].Tags, r.nodes[2].Tags = []string{"keep"}, []string{"keep"}, []string{"keep"}
	r.group.group.TagFilter = domain.TagFilter{Tags: []string{"keep"}}
	r.Service.repos.Settings = fakeSettings{s: ports.UISettings{SubRegionFlagPrefix: true}}
	return r
}

// separatorsStrategyFleet: nodes that tie on sort_order across regions under a
// non-default sort strategy, one node-bound separator the group qualifies for
// and one it does not.
func separatorsStrategyFleet(t *testing.T) *lineOrderRender {
	t.Helper()
	seps := []*domain.SeparatorEntry{
		{ID: 1, DisplayName: "---- bound, visible ----", SortOrder: 10, Enabled: true, Mode: domain.SeparatorModeNodeBound, NodeIDs: []int64{8}},
		{ID: 2, DisplayName: "---- bound, hidden ----", SortOrder: 10, Enabled: true, Mode: domain.SeparatorModeNodeBound, NodeIDs: []int64{999}},
		{ID: 3, DisplayName: "---- global ----", SortOrder: 20, Enabled: true, Mode: domain.SeparatorModeGlobal},
	}
	r := newLineOrderRender(t, seps,
		spec(9, "Nine", 10, "US", "n1"),
		spec(8, "Eight", 10, "AU", "e1"),
		spec(7, "Seven", 10, "JP"),
		spec(6, "Six", 20, "DE", "s1"),
	)
	r.group.group.Layout = domain.Layout{DefaultSortStrategy: "by_id", Sort: []domain.SortEntry{{NodeID: 6, Weight: 1}}}
	return r
}

var goldenScenarios = []struct {
	name  string
	build func(*testing.T) *lineOrderRender
}{
	{"line-kinds", lineKindsFleet},
	{"filtered-flagged", filteredFlaggedFleet},
	{"separators-strategy", separatorsStrategyFleet},
}

// TestUpgradeWithoutPositionsRendersIdenticalBytesForEveryScenario extends the
// compatibility guarantee to every kind of line and the layout features around
// them. Goldens under testdata/line_order/<scenario>/ were generated by running
// this test with PSP_UPDATE_GOLDEN=1 in a checkout of the commit BEFORE any
// ordering code existed (a source export of that commit with these two test
// files added), never from the ordering code itself.
func TestUpgradeWithoutPositionsRendersIdenticalBytesForEveryScenario(t *testing.T) {
	for _, sc := range goldenScenarios {
		for _, ct := range allClientTypes {
			t.Run(sc.name+"/"+string(ct), func(t *testing.T) {
				r := sc.build(t)
				out, err := r.RenderForUser(context.Background(), r.user, ct)
				if err != nil {
					t.Fatal(err)
				}
				path := filepath.Join("testdata", "line_order", sc.name, string(ct)+".golden")
				if os.Getenv("PSP_UPDATE_GOLDEN") != "" {
					if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
						t.Fatal(err)
					}
					if err := os.WriteFile(path, out.Body, 0o644); err != nil {
						t.Fatal(err)
					}
					return
				}
				want, err := os.ReadFile(path)
				if err != nil {
					t.Fatal(err)
				}
				if string(want) != string(out.Body) {
					t.Fatalf("%s/%s body changed without any line position stored\nwant:\n%s\ngot:\n%s", sc.name, ct, want, out.Body)
				}
			})
		}
	}
}
