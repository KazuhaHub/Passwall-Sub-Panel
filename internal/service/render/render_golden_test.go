// goldenScenario describes one synthetic render over the reference node (a
// VLESS node "A" with the relay line "A B"). Empty templates use the reference
// ones.
type goldenScenario struct {
	name     string
	mihomo   string
	singBox  string
	shared   string
	personal string
	members  map[string][]domain.ProxyGroupMember
	options  map[string]domain.ProxyGroupOptions
	order    []string
	subRules []domain.MihomoSubRule
	rematch  []domain.MihomoRematchOutbound
	mutate   func(s *Service, n *domain.Node, u *domain.User, rule *domain.RuleSet)
}

func (sc goldenScenario) build(t testing.TB) (*Service, *domain.User) {
	t.Helper()
	s, n, u, rule := referenceRenderFixture(t)
	rule.Content = sc.shared
	rule.MihomoSubRules, rule.MihomoRematchOutbounds = sc.subRules, sc.rematch
	rule.ProxyGroupOrder = sc.order
	if sc.members != nil {
		rule.ProxyGroupMembers = sc.members
	}
	if sc.options != nil {
		rule.ProxyGroupOptions = sc.options
	}
	u.PersonalRules = sc.personal
	templates := map[domain.ClientType]string{domain.ClientMihomo: referenceMihomoTemplate, domain.ClientSingBox: referenceSingBoxTemplate}
	if sc.mihomo != "" {
		templates[domain.ClientMihomo] = sc.mihomo
	}
	if sc.singBox != "" {
		templates[domain.ClientSingBox] = sc.singBox
	}
	s.repos.Template = referenceTemplateRepo{content: templates}
	if sc.mutate != nil {
		sc.mutate(s, n, u, rule)
	}
	return s, u
}

// goldenSeedRuleSet is the shipped default rule set with every field the YAML
// repository would load, not only its content.
func goldenSeedRuleSet(t testing.TB) *domain.RuleSet {
	t.Helper()
	raw, err := os.ReadFile("../../seed/files/rulesets/default-rules.yaml")
	if err != nil {
		t.Fatal(err)
	}
	var file struct {
		Slug            string   `yaml:"slug"`
		ProxyGroupOrder []string `yaml:"proxy_group_order"`
		Content         string   `yaml:"content"`
	}
	if err := yaml.Unmarshal(raw, &file); err != nil {
		t.Fatal(err)
	}
	return &domain.RuleSet{Slug: file.Slug, Enabled: true, ProxyGroupOrder: file.ProxyGroupOrder, Content: file.Content}
}

func goldenSeed(mutate func(s *Service, u *domain.User, rule *domain.RuleSet)) func(testing.TB) (*Service, *domain.User) {
	return func(t testing.TB) (*Service, *domain.User) {
		t.Helper()
		s, _, u, _ := referenceRenderFixture(t)
		rule := goldenSeedRuleSet(t)
		s.repos.Template = referenceTemplateRepo{content: map[domain.ClientType]string{
			domain.ClientMihomo:  readTemplateContent(t, "../../seed/files/templates/default-mihomo.yaml"),
			domain.ClientSingBox: readTemplateContent(t, "../../seed/files/templates/default-sing-box.yaml"),
		}}
		s.repos.RuleSet = referenceRuleRepo{rule: rule}
		if mutate != nil {
			mutate(s, u, rule)
		}
		return s, u
	}
}

