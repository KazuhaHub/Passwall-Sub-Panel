// The render golden pins the exact bytes of a subscription. Every subscriber's
// client configuration comes out of this package, so work that only makes a
// render cheaper must leave each of these documents byte-for-byte unchanged,
// and each failing input failing with the same error text.
//
// testdata/render_golden.json maps "<case>/<client type>" to the SHA-256 of the
// rendered body, or to "error: <text>" for an input that must fail. The file
// was generated by running this test against the production code of commit
// 72a2d43f (origin/main before the render-cost work) with
// PSP_UPDATE_RENDER_GOLDEN=1, then copied here unchanged. Regenerate it only
// for a deliberate change of rendered output, never to make an optimisation
// pass.
//
// A render is deterministic for fixed inputs, with one exception that the
// golden masks rather than hides: the per-render line token
// ("psp-line-<uuid>-<node>:<line>"). It is replaced by the public name wherever
// a line is referenced, but it survives in two places: an error that quotes a
// rule ("invalid rule \"psp-line-…-7:direct\""), and a template that copies its
// rules into another key through a YAML alias, where the copy is not a rule
// slot and keeps the token. Both are compared with the random part masked.
const renderGoldenPath = "testdata/render_golden.json"

