// Real-browser acceptance against a dedicated local vlessRoute V2 fixture.
// Never run against a production or the user's ordinary manual-test instance.
import assert from 'node:assert/strict'
import { mkdtemp } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { pathToFileURL } from 'node:url'

const base = process.env.PSP_V2_PANEL_URL
assert.equal(process.env.PSP_V2_UI_TEST, 'isolated-acceptance-fixture')
const target = new URL(base)
assert.equal(target.hostname, '127.0.0.1')
assert.equal(target.protocol, 'http:')
const password = process.env.PSP_V2_ADMIN_PASSWORD
assert.ok(password)
const build = await (await fetch(`${base}/api/version`)).json()
assert.equal(build.version, 'vlessroute-v2-acceptance')
const { chromium } = await import(pathToFileURL(process.env.PLAYWRIGHT_MODULE).href)
const output = await mkdtemp(join(tmpdir(), 'psp-v2-ui-'))
const browser = await chromium.launch({ headless: true })
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, locale: 'zh-CN' })
const page = await context.newPage()
const errors = []
page.on('pageerror', error => errors.push(error.message))
try {
  await page.goto(`${base}/login`)
  await page.getByRole('textbox').first().fill('admin')
  await page.locator('input[type="password"]').fill(password)
  await page.locator('button[type="submit"]').first().click()
  await page.waitForURL(url => !url.pathname.includes('login'))
  await page.goto(`${base}/admin/nodes`)
  const editNode = async () => {
    const row = page.getByRole('row').filter({ has: page.getByText('A-false', { exact: true }) })
    await row.getByRole('button', { name: /^(编辑|Edit)$/ }).click()
    return page.getByRole('dialog')
  }
  let dialog = await editNode()
  await dialog.getByRole('tab', { name: /^(VLESS 路由线路|VLESS routing lines)$/ }).click()
  await dialog.getByRole('textbox', { name: /线路名称|Line name/ }).first().waitFor()
  const savedName = await dialog.getByRole('textbox', { name: /线路名称|Line name/ }).first().inputValue()
  await dialog.getByRole('combobox', { name: /^(线路出站|Line outbound)/ }).first().click()
  const optionNames = await page.getByRole('option').allTextContents()
  assert.ok(optionNames.includes('direct [freedom]'))
  assert.ok(optionNames.includes('blocked [blackhole]'))
  assert.ok(optionNames.every(name => /^[^\[\]]+ \[[^\[\]]+\]$/.test(name)))
  assert.equal(await page.getByRole('option', { name: /选择已有出站|Select an existing outbound/ }).count(), 0)
  await page.getByRole('option', { name: 'direct [freedom]', exact: true }).click()
  await dialog.getByRole('textbox', { name: /线路名称|Line name/ }).first().fill('UI-check')
  const write = page.waitForResponse(response => response.url().endsWith('/vless-route-lines') && response.request().method() === 'PUT')
  await dialog.locator('button[type="submit"][form="node-form"]').click()
  const saved = await (await write).json()
  assert.equal(saved.state.status, 'applied')
  await page.getByRole('dialog').last().waitFor({ state: 'hidden' })
  dialog = await editNode()
  await dialog.getByRole('tab', { name: /^(VLESS 路由线路|VLESS routing lines)$/ }).click()
  await dialog.getByRole('textbox', { name: /线路名称|Line name/ }).first().waitFor()
  assert.equal(await dialog.getByRole('textbox', { name: /线路名称|Line name/ }).first().inputValue(), 'UI-check')
  for (const width of [390, 768, 1440]) {
    await page.setViewportSize({ width, height: 1000 })
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1), `document overflow at ${width}`)
    assert.ok(await dialog.locator('.MuiDialogContent-root').evaluate(element => element.scrollWidth <= element.clientWidth + 1), `node dialog overflow at ${width}`)
    const name = await dialog.getByRole('textbox', { name: /线路名称|Line name/ }).first().boundingBox()
    const toggle = await dialog.getByRole('switch').first().boundingBox()
    const remove = await dialog.getByRole('button', { name: /删除该线路|Remove this line/ }).first().boundingBox()
    const up = await dialog.getByRole('button', { name: /上移|Move up/, exact: true }).first().boundingBox()
    const down = await dialog.getByRole('button', { name: /下移|Move down/, exact: true }).first().boundingBox()
    const outbound = await dialog.getByRole('combobox', { name: /^(线路出站|Line outbound)/ }).first().boundingBox()
    assert.ok(name && toggle && remove && up && down && outbound)
    assert.ok(Math.abs(name.y + name.height / 2 - up.y - up.height / 2) < 3, `up must share name row at ${width}`)
    assert.ok(Math.abs(name.y + name.height / 2 - down.y - down.height / 2) < 3, `down must share name row at ${width}`)
    assert.ok(toggle.x < up.x && up.x < down.x && down.x < remove.x, `enable, up, down, delete order at ${width}`)
    assert.equal(await dialog.getByText(/^route \d+$/).count(), 0)
    assert.equal(await dialog.getByText(/路由已回读确认|Routing readback confirmed/).count(), 0)
    assert.ok(Math.abs(name.y + name.height / 2 - toggle.y - toggle.height / 2) < 3, `enable must share name row at ${width}`)
    assert.ok(Math.abs(name.y + name.height / 2 - remove.y - remove.height / 2) < 3, `delete must share name row at ${width}`)
    assert.ok(outbound.y >= name.y + name.height, `outbound must follow name row at ${width}`)
    await page.screenshot({ path: join(output, `node-lines-${width}.png`), animations: 'disabled' })
  }
  await page.setViewportSize({ width: 1440, height: 1000 })
  await dialog.getByRole('textbox', { name: /线路名称|Line name/ }).first().fill(savedName)
  const restore = page.waitForResponse(response => response.url().endsWith('/vless-route-lines') && response.request().method() === 'PUT')
  await dialog.locator('button[type="submit"][form="node-form"]').click()
  assert.equal((await (await restore).json()).state.status, 'applied')
  await page.getByRole('dialog').last().waitFor({ state: 'hidden' })

  const token = await page.evaluate(() => localStorage.getItem('psp_access'))
  const headers = { Authorization: `Bearer ${token}`, 'Content-Type': 'application/json' }
  const rule = { slug: 'v2-ui-check', name: 'V2 UI QA', enabled: false, sort: 0, direct_subscription_domain: false, content: '- MATCH,UI-Pick', proxy_group_order: ['UI-Pick'], proxy_group_members: { 'UI-Pick': [{ kind: 'builtin', value: 'DIRECT' }] } }
  const created = await fetch(`${base}/api/admin/rules/${rule.slug}`, { method: 'PUT', headers, body: JSON.stringify(rule) })
  assert.ok(created.ok, 'temporary unbound rule setup failed')
  await page.goto(`${base}/admin/rules`)
  const ruleRow = page.getByRole('row').filter({ has: page.getByText('V2 UI QA', { exact: true }) })
  await ruleRow.getByRole('button', { name: /编辑规则集|Edit rule set/ }).click()
  dialog = page.getByRole('dialog')
  await dialog.getByRole('tab', { name: /代理组成员|Proxy group members/ }).click()
  // The inspector also includes the default selector. Select the fixture
  // group explicitly rather than relying on the initially selected group.
  await dialog.getByRole('button').filter({ has: page.getByText('UI-Pick', { exact: true }) }).click()
  await dialog.getByRole('heading', { name: 'UI-Pick', exact: true }).waitFor()
  assert.equal(await dialog.getByText(/按项目默认顺序显示|Shown in the project default order/).count(), 0)
  const category = dialog.getByRole('combobox').filter({ hasText: /按节点选择|Select by node/ })
  await category.click()
  const categoryNames = await page.getByRole('option').allTextContents()
  const zhCategories = ['按节点选择', '按线路选择', '其余线路', '按区域匹配', '按标签匹配', '内置出站', '引用代理组', 'Rematch 出站']
  const enCategories = ['Select by node', 'Select by line', 'Remaining lines', 'Match by region', 'Match by tag', 'Built-in outbound', 'Reference proxy group', 'Rematch outbound']
  assert.ok(JSON.stringify(categoryNames) === JSON.stringify(zhCategories) || JSON.stringify(categoryNames) === JSON.stringify(enCategories), 'all member category names are updated')
  await page.getByRole('option', { name: /按线路选择|Select by line/ }).click()
  const nodePicker = dialog.getByRole('combobox', { name: /^(节点|Node)$/ })
  const linePicker = dialog.getByRole('combobox', { name: /^(线路|Line)$/ })
  assert.equal(await linePicker.isDisabled(), true)
  await nodePicker.fill('A-false')
  await page.getByRole('option', { name: 'A-false', exact: true }).click()
  await linePicker.fill('[')
  assert.ok(await page.getByRole('option', { name: /^(\[直连线路\]|\[Direct line\])$/ }).isVisible())
  assert.equal(await page.getByRole('option', { name: /A-false \[直连线路\]|A-false \[Direct line\]/ }).count(), 0)
  await linePicker.fill('DIRECT')
  await page.getByRole('option', { name: /^(DIRECT \[VLESS 路由\]|DIRECT \[VLESS route\])$/ }).click()
  await dialog.getByRole('button', { name: /^(添加|Add)$/ }).click()
  await dialog.getByRole('button', { name: /^(删除|Delete) DIRECT$/ }).click()
  for (const width of [390, 768, 1440]) {
    await page.setViewportSize({ width, height: 1000 })
    await nodePicker.scrollIntoViewIfNeeded()
    const nodeBox = await nodePicker.locator('..').boundingBox()
    const lineBox = await linePicker.locator('..').boundingBox()
    assert.ok(nodeBox && lineBox && Math.abs(nodeBox.width - lineBox.width) < 1, `equal picker widths at ${width}`)
    assert.ok(nodeBox.x < lineBox.x && Math.abs(nodeBox.y - lineBox.y) < 1, `node then line on the same row at ${width}`)
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1), `rule editor overflow at ${width}`)
    assert.ok(await dialog.locator('.MuiDialogContent-root').evaluate(element => element.scrollWidth <= element.clientWidth + 1), `dialog content overflow at ${width}`)
    assert.equal(await dialog.getByText(/^line:1:/).count(), 0, `no inline identity at ${width}`)
    const memberName = dialog.getByText('A-false DIRECT', { exact: true }).last()
    const identity = await memberName.getAttribute('title')
    assert.match(identity, /^line:1:/)
    const nameBox = await memberName.boundingBox()
    const nameArea = await memberName.locator('..').boundingBox()
    assert.ok(nameBox && nameArea && nameBox.width < nameArea.width, `tooltip trigger hugs the member name at ${width}`)
    await memberName.hover()
    const tooltip = page.getByRole('tooltip')
    await tooltip.waitFor()
    assert.equal(await tooltip.textContent(), identity, `hover reveals full identity at ${width}`)
    if (width === 1440) {
      const triggerBox = await memberName.boundingBox()
      const tooltipBox = await tooltip.boundingBox()
      assert.ok(triggerBox && tooltipBox && Math.abs(triggerBox.x + triggerBox.width / 2 - tooltipBox.x - tooltipBox.width / 2) < 2, 'tooltip is centered over the name, not the row')
    }
    await page.screenshot({ path: join(output, `specific-line-${width}.png`), animations: 'disabled' })
    await page.mouse.move(5, 5)
    await tooltip.waitFor({ state: 'hidden' })
  }
  const ruleWrite = page.waitForResponse(response => response.url().endsWith(`/rules/${rule.slug}`) && response.request().method() === 'PUT')
  await dialog.locator('button[type="submit"][form="rules-form"]').click()
  const persisted = await (await ruleWrite).json()
  assert.equal(persisted.proxy_group_members['UI-Pick'].length, 1)
  assert.equal(persisted.proxy_group_members['UI-Pick'][0].kind, 'line')
  assert.ok(persisted.proxy_group_members['UI-Pick'][0].line_id)
  await page.getByRole('dialog').last().waitFor({ state: 'hidden' })
  await ruleRow.getByRole('button', { name: /编辑规则集|Edit rule set/ }).click()
  dialog = page.getByRole('dialog')
  await dialog.getByRole('tab', { name: /代理组成员|Proxy group members/ }).click()
  await dialog.getByRole('button').filter({ has: page.getByText('UI-Pick', { exact: true }) }).click()
  await dialog.getByRole('heading', { name: 'UI-Pick', exact: true }).waitFor()
  assert.ok(await dialog.getByText('A-false DIRECT', { exact: true }).last().isVisible())
  const expectedIdentity = `line:${persisted.proxy_group_members['UI-Pick'][0].node_id}:${persisted.proxy_group_members['UI-Pick'][0].line_id}`
  assert.equal(await dialog.getByText(expectedIdentity, { exact: true }).count(), 0)
  await dialog.getByText('A-false DIRECT', { exact: true }).last().hover()
  await page.getByRole('tooltip').waitFor()
  assert.equal(await page.getByRole('tooltip').textContent(), expectedIdentity)
  assert.deepEqual(errors, [])
  console.log(JSON.stringify({ status: 'pass', commit: build.commit, output, widths: [390, 768, 1440], pageErrors: errors, relayStyleLayout: true, directSave: true, outboundOptionFormat: true, nodeSaveReopen: true, specificLineRuleSaveReopen: true, equalWidthNodeLinePickers: true, directLineLabelOnly: true, memberIdentityOnHoverOnly: true }))
} catch (error) {
  await page.screenshot({ path: join(output, 'failure.png') }).catch(() => {})
  console.error('UI diagnostics:', output)
  throw error
} finally {
  await browser.close()
}
